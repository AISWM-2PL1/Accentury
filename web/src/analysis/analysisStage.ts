/**
 * 폴링 상태 → 3단계 진행 (KAN-161 3단계).
 *
 * 대기 화면은 시안에서 "곡선 추출 → 분포 비교 → 등급 계산" 세 칸으로 그려진다. 서버는 그런
 * 단계를 주지 않는다 — `/analyses`가 문항별 상태를, `/complete`가 READY 여부를 줄 뿐이다.
 * 그래서 단계는 **이미 있는 값에서 파생**한다. 상태 머신에 단계를 새로 심지 않는 이유는
 * 그것이 곧 서버와 어긋날 수 있는 두 번째 진행 개념이 되기 때문이다.
 *
 * ## 무엇을 무엇에 걸었나
 *
 * | 단계 | 뜻 | 파생 근거 |
 * |---|---|---|
 * | 1 곡선 추출 | 음성 문항이 아직 분석 중 | 완료된 음성 < 전체 음성 |
 * | 2 분포 비교 | 음성은 다 끝났고 집계를 기다린다 | 음성 전부 완료, `/complete`는 아직 READY가 아님 |
 * | 3 등급 계산 | 결과가 확정됐다 | `READY` |
 *
 * 세 단계가 서버의 실제 처리 단계와 1:1은 아니다. 사용자에게 필요한 것은 "어디쯤인지"이고
 * 그 셋은 실제로 이 순서로 일어난다 — 문항 분석이 끝나야 집계가 돌고, 집계가 끝나야 등급이
 * 나온다. 없는 진행을 지어내지 않으면서 기다림에 눈금을 준다.
 *
 * ## 왜 순수 함수인가
 *
 * 입력이 셋뿐이라 조합을 전부 테스트로 고정할 수 있다. 화면 안에 삼항 연산자로 두면 "음성이
 * 0개인 세션"이나 "READY인데 완료가 덜 세어진" 경계를 확인하려고 폴링 전체를 세워야 한다.
 */

/** 화면에 그릴 단계 이름. 순서가 곧 번호다 */
export const ANALYSIS_STAGES = ['곡선 추출', '분포 비교', '등급 계산'] as const

export interface AnalysisStageInput {
  /** 결과가 확정됐는가 (`WaitingStatus.kind === 'READY'`) */
  ready: boolean
  /** 분석이 끝난 음성 문항 수 */
  completedVoice: number
  /** 전체 음성 문항 수 */
  totalVoice: number
}

/**
 * 지금 진행 중인 단계 (1-기반).
 *
 * 완료된 단계는 이 값보다 작은 번호다 — 화면은 그 대소만 보고 동그라미를 그린다.
 * `ready`면 3을 돌려주는데, 3이 "끝난" 것이 아니라 "지금 등급을 계산 중"이라는 뜻이다:
 * READY 직후 화면은 곧 결과로 넘어가므로 마지막 칸이 완료로 바뀐 모습은 사람이 볼 틈이 없다.
 */
export function analysisStage({ ready, completedVoice, totalVoice }: AnalysisStageInput): 1 | 2 | 3 {
  if (ready) return 3
  /*
   * 음성 문항이 없는 세션은 뽑을 곡선도 없다. 0 < 0이 거짓이라 그냥 두면 1단계에 머무는데,
   * 영원히 "곡선 추출 중"인 화면이 된다 — 기다리는 것은 집계이므로 2단계가 맞다.
   */
  if (totalVoice <= 0) return 2
  return completedVoice < totalVoice ? 1 : 2
}
