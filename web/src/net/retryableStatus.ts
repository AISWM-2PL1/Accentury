/**
 * 봉투 없는 HTTP 실패의 재시도 판정 (KAN-170에서 사본 두 개를 여기로 모았다).
 *
 * 서버가 오류 봉투(§2.3)를 실어 주면 `retryable`은 그쪽 값이 정답이다. 문제는 봉투가 아예
 * 없는 실패다 — WAF의 기본 403, CloudFront·ALB가 본문 없이 돌려보내는 4xx처럼 우리 애플리케이션에
 * 닿지도 못한 응답에는 읽을 봉투가 없다. 그때 클라이언트가 가진 단서는 상태 코드뿐이고,
 * **그 판정의 유일한 정의가 이 함수다.**
 *
 * 408·429·5xx만 재시도 가능이다. 시간이나 부하가 원인이라 잠시 뒤 같은 요청이 통할 수 있다.
 * 나머지 4xx는 요청 자체가 서버가 받아 줄 수 없는 모양이라, 다시 보내도 같은 답이 온다 —
 * 재시도 버튼을 띄우면 사용자가 안 될 일을 반복하게 된다.
 *
 * 네이티브 `UploadClient.kt`·`SessionClient.kt`가 같은 규칙을 쓴다. 같은 실패를 앱에서는
 * 재시도하고 웹에서는 포기하면 사용자에게는 기기 탓으로 보인다.
 */

/** 408·429·5xx는 잠시 뒤 같은 요청이 통할 수 있는 실패다. 4xx 나머지는 다시 보내도 같다 */
export function isRetryableStatus(status: number): boolean {
  return status >= 500 || status === 408 || status === 429
}
