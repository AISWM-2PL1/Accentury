package app.accentury.backend.analytics;

/**
 * 이 트래픽이 실사용자인지 합성인지 (KAN-138).
 * <p>
 * 익명 집계 카운터(KAN-106)를 가르는 축이다. 전 구간 E2E 스모크는 prod에서도 돌아야 하는데
 * (KAN-138 AC), 세션 생성과 완주가 카운터를 올리고 그 카운터는 개인 결과가 24시간 뒤
 * 파기돼도 남는 <b>유일한 영속 데이터</b>다. 표시가 없으면 스모크 1회마다 완주율과 등급
 * 분포가 영구히 흔들리고, 일자 합계라 나중에 빼낼 수도 없다 (Codex sol 리뷰 P2).
 * <p>
 * <b>버리지 않고 나눈다.</b> 리포트(KAN-20)가 "오늘 응시 47건" 옆에 "스모크 2건"을 볼 수
 * 있어야, 숫자가 왜 그런지 물었을 때 답이 있다. 0으로 지우면 그 질문에 답할 수 없다.
 * <p>
 * 판정은 세션 생성 시점 <b>한 번</b>이고({@link SyntheticTraffic}) 이후 완주 카운터는 세션
 * 행의 값을 따라간다. 요청마다 표시를 요구하면 하나가 빠졌을 때 응시는 제외되고 완주는
 * 섞이는 반쪽 상태가 된다.
 */
public enum Traffic {

    /** 실제 사용자. 표시가 없으면 이쪽이다 - 안전한 기본값이다. */
    REAL,

    /** 검증용 합성 트래픽 (E2E 스모크). 관리자 시크릿으로 인증된 요청만 이렇게 표시된다. */
    SYNTHETIC
}
